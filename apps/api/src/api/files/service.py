"""Files service: policy-checked writes, scope-aware reads, keyset listing.

Every function takes the ``store`` port and the bucket explicitly, so the
service holds no object-store global and tests inject ``FakeObjectStore``.
The row's ``tenant_id`` matches the ambient scope or the write runs inside
``tenant_scope(<row tenant>)``, so the flush guard always passes.
"""

